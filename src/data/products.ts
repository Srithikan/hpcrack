const STORAGE_KEY = 'harini_priya_products_2026_v2';

export function loadStoredProducts(): Product[] {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (!raw) return INITIAL_PRODUCTS;
    const parsed = JSON.parse(raw);
    if (Array.isArray(parsed) && parsed.length === INITIAL_PRODUCTS.length) {
      return parsed;
    }
  } catch (e) {
    console.error('Error loading stored products, using defaults', e);
  }
  return INITIAL_PRODUCTS;
}

export function saveStoredProducts(products: Product[]): void {
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(products));
  } catch (e) {
    console.error('Error saving products', e);
  }
}

export function resetStoredProducts(): Product[] {
  try {
    localStorage.removeItem(STORAGE_KEY);
  } catch (e) {
    console.error('Error resetting products', e);
  }
  return INITIAL_PRODUCTS;
}
